/**
 * ชื่อกลุ่มและชนิดข้อมูลของรายงาน COPD — ส่วนที่ทั้งสองฝั่งต้องเห็นตรงกัน
 *
 * แยกออกจาก lib/his/copd-stats.ts เพราะไฟล์นั้นเป็น server-only (ต่อฐานข้อมูล)
 * ถ้าหน้าจอ import รายชื่อกลุ่มจากที่นั่น ตัว bundler จะลาก mysql2 เข้าไปใน
 * client bundle แล้ว build ล้ม — ที่นี่มีแต่ค่าคงที่กับชนิดข้อมูล ไม่มี import
 * ที่แตะฐานข้อมูลเลย จึงปลอดภัยทั้งสองฝั่ง (แบบเดียวกับ sepsis-groups.ts)
 */

/**
 * ช่วงอายุของผู้ป่วยใน COPD ตามที่ได้รับมา
 *
 * ห้าช่วงนี้**แบ่งผู้ป่วยออกจากกันหมด** ไม่ซ้อนกันเลย ต่างจากกลุ่มของหน้า Sepsis
 * ที่เป็นธงซ้อนกันได้ — ผลรวมของห้าช่วงจึงเท่ากับผู้ป่วยทั้งหมด และเอามาวางเป็น
 * แท่งซ้อนกันได้จริง
 */
export const COPD_AGE_BANDS = ['under15', 'age15to39', 'age40to49', 'age50to59', 'age60up'] as const

export type CopdAgeBand = (typeof COPD_AGE_BANDS)[number]

/**
 * ขอบเขตการนับผู้ป่วยปอดบวม — ต่างกันที่ประเภทการวินิจฉัย
 *
 * any = มีรหัสปอดบวมเป็นการวินิจฉัยประเภทใดก็ได้ ตามที่คิวรีที่ได้รับมาทำจริง
 * primary = เฉพาะโรคหลักหรือโรคร่วมแรกรับ (diagtype 1, 2) ตามที่หัวคอลัมน์ของ
 * คิวรีนั้นเขียนไว้ว่า “PDx หรือ SDx”
 *
 * สองอย่างนี้ไม่ตรงกันในคิวรีต้นฉบับ จึงให้เลือกดูได้ทั้งคู่แทนที่จะเดาแทน
 */
export const PNEUMONIA_SCOPES = ['any', 'primary'] as const

export type PneumoniaScope = (typeof PNEUMONIA_SCOPES)[number]

export type CopdCount = {
  /** การนอนโรงพยาบาล (AN) ที่เข้ากลุ่มนี้ */
  total: number
  /** ในกลุ่มนั้น ที่จำหน่ายด้วยสถานะเสียชีวิต (dchtype 08, 09) */
  dead: number
}

export type CopdPeriod = {
  /** คีย์ของช่วง — ปีงบเป็น '2569' เดือนเป็น '2026-01' */
  key: string
  partial: boolean
  /** ผู้ป่วยปอดบวม แยกตามขอบเขตการวินิจฉัยสองแบบ */
  pneumonia: Record<PneumoniaScope, CopdCount>
  /**
   * ผู้ป่วยปอดบวมที่นับได้ด้วยรายการรหัส **ตามที่คิวรีต้นฉบับเขียนไว้จริง**
   *
   * เก็บไว้เพื่อให้หน้าจอบอกได้ว่าตัวเลขที่แก้แล้วต่างจากของเดิมเท่าไร ไม่ได้
   * เอาไปคิดอัตราที่ไหน — รายการรหัสในคิวรีนั้นเขียนจุดทศนิยมไว้ (J10.0, J18)
   * ซึ่งไม่ตรงกับรูปแบบที่ฐานเก็บ (J100, J180) จึงจับไม่ได้เลยสักแถว
   */
  pneumoniaAsWritten: CopdCount
  /** ผู้ป่วยใน COPD — J44 เป็นโรคหลัก (diagtype 1) */
  copd: CopdCount
  /** COPD แยกตามช่วงอายุ — ห้าช่วงบวกกันได้เท่ากับ copd */
  ages: Record<CopdAgeBand, CopdCount>
  /**
   * COPD ที่ไม่มีอายุในทะเบียน an_stat
   *
   * วัดแล้วเป็นศูนย์ทุกปีงบ แต่ต้องมีที่ให้มันอยู่ ไม่ใช่ปล่อยให้ผลรวมของ
   * ห้าช่วงอายุน้อยกว่ายอด COPD แล้วไม่มีใครรู้ว่าหายไปไหน
   */
  ageUnknown: CopdCount
  /**
   * ผู้ป่วยในทั้งหมดที่จำหน่ายในช่วงนี้ — ตัวหารของ "อัตราผู้ป่วยใน"
   *
   * ตัวชี้วัดระดับชาติคิดต่อแสนประชากร แต่ HIS ไม่มีทะเบียนประชากรรายปีที่ใช้
   * เป็นตัวหารได้ (ตาราง person มีทุกคนที่เคยลงทะเบียน ไม่ได้แยกปีและไม่ได้ตัด
   * คนที่ย้ายหรือเสียชีวิต) จึงรายงานเป็นสัดส่วนของผู้ป่วยในทั้งหมดแทน พร้อม
   * บอกคนอ่านว่าคนละตัวหารกับตัวชี้วัดระดับชาติ
   */
  admissions: number
}
