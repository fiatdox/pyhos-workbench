/**
 * ชื่อกลุ่มและชนิดข้อมูลของรายงาน COPD — ส่วนที่ทั้งสองฝั่งต้องเห็นตรงกัน
 *
 * แยกออกจาก lib/his/copd-stats.ts เพราะไฟล์นั้นเป็น server-only (ต่อฐานข้อมูล)
 * ถ้าหน้าจอ import รายชื่อกลุ่มจากที่นั่น ตัว bundler จะลาก mysql2 เข้าไปใน
 * client bundle แล้ว build ล้ม — ที่นี่มีแต่ค่าคงที่กับชนิดข้อมูล ไม่มี import
 * ที่แตะฐานข้อมูลเลย จึงปลอดภัยทั้งสองฝั่ง (แบบเดียวกับ sepsis-groups.ts)
 */

/**
 * ช่วงอายุของผู้ป่วยใน COPD ตามที่ได้รับมา
 *
 * ห้าช่วงนี้**แบ่งผู้ป่วยออกจากกันหมด** ไม่ซ้อนกันเลย ต่างจากกลุ่มของหน้า Sepsis
 * ที่เป็นธงซ้อนกันได้ — ผลรวมของห้าช่วงจึงเท่ากับผู้ป่วยทั้งหมด และเอามาวางเป็น
 * แท่งซ้อนกันได้จริง
 */
export const COPD_AGE_BANDS = ['under15', 'age15to39', 'age40to49', 'age50to59', 'age60up'] as const

export type CopdAgeBand = (typeof COPD_AGE_BANDS)[number]

/**
 * ขอบเขตการนับผู้ป่วยปอดบวม — ต่างกันที่ประเภทการวินิจฉัย
 *
 * any = มีรหัสปอดบวมเป็นการวินิจฉัยประเภทใดก็ได้ ตามที่คิวรีที่ได้รับมาทำจริง
 * primary = เฉพาะโรคหลักหรือโรคร่วมแรกรับ (diagtype 1, 2) ตามที่หัวคอลัมน์ของ
 * คิวรีนั้นเขียนไว้ว่า “PDx หรือ SDx”
 *
 * สองอย่างนี้ไม่ตรงกันในคิวรีต้นฉบับ จึงให้เลือกดูได้ทั้งคู่แทนที่จะเดาแทน
 */
export const PNEUMONIA_SCOPES = ['any', 'primary'] as const

export type PneumoniaScope = (typeof PNEUMONIA_SCOPES)[number]

export type CopdCount = {
  /** การนอนโรงพยาบาล (AN) ที่เข้ากลุ่มนี้ */
  total: number
  /** ในกลุ่มนั้น ที่จำหน่ายด้วยสถานะเสียชีวิต (dchtype 08, 09) */
  dead: number
}

/**
 * โรคทางเดินหายใจเรื้อรังที่รายงานผู้ป่วยในแยกตามช่วงอายุ
 *
 * สองโรคนี้ถามคำถามเดียวกันและมาจากคิวรีรูปเดียวกัน ต่างแค่ช่วงรหัส — COPD คือ
 * J44 ส่วนหืดคือ J45-J46 ทั้งคู่นับเฉพาะที่เป็น**โรคหลัก** จึงแยกกันเสมอ
 * (หนึ่งการนอนมีโรคหลักได้รหัสเดียว) ยอดของสองโรคบวกกันได้ ไม่นับซ้ำ
 */
export const COPD_DISEASES = ['copd', 'asthma'] as const

export type CopdDisease = (typeof COPD_DISEASES)[number]

/** ผู้ป่วยในของโรคหนึ่ง ในหนึ่งช่วงเวลา แยกตามช่วงอายุ */
export type CopdDiseaseStats = {
  /** ยอดรวมของโรคนี้ — ห้าช่วงอายุบวก ageUnknown ได้เท่านี้พอดี */
  total: CopdCount
  ages: Record<CopdAgeBand, CopdCount>
  /**
   * ผู้ป่วยที่ไม่มีอายุในทะเบียน an_stat
   *
   * วัดแล้วเป็นศูนย์ทุกปีงบ แต่ต้องมีที่ให้มันอยู่ ไม่ใช่ปล่อยให้ผลรวมของ
   * ห้าช่วงอายุน้อยกว่ายอดรวมแล้วไม่มีใครรู้ว่าหายไปไหน
   */
  ageUnknown: CopdCount
}

export type CopdPeriod = {
  /** คีย์ของช่วง — ปีงบเป็น '2569' เดือนเป็น '2026-01' */
  key: string
  partial: boolean
  /** ผู้ป่วยปอดบวม แยกตามขอบเขตการวินิจฉัยสองแบบ */
  pneumonia: Record<PneumoniaScope, CopdCount>
  /**
   * ผู้ป่วยปอดบวมที่นับได้ด้วยรายการรหัส **ตามที่คิวรีต้นฉบับเขียนไว้จริง**
   *
   * เก็บไว้เพื่อให้หน้าจอบอกได้ว่าตัวเลขที่แก้แล้วต่างจากของเดิมเท่าไร ไม่ได้
   * เอาไปคิดอัตราที่ไหน — รายการรหัสในคิวรีนั้นเขียนจุดทศนิยมไว้ (J10.0, J18)
   * ซึ่งไม่ตรงกับรูปแบบที่ฐานเก็บ (J100, J180) จึงจับไม่ได้เลยสักแถว
   */
  pneumoniaAsWritten: CopdCount
  /**
   * ผู้ป่วยในของแต่ละโรค แยกตามช่วงอายุ — COPD (J44) และหืด (J45-J46)
   *
   * ทั้งคู่นับเฉพาะที่ลงเป็นโรคหลัก (diagtype 1) ตามคิวรีที่ได้รับมา
   */
  inpatient: Record<CopdDisease, CopdDiseaseStats>
  /**
   * ผู้ป่วยในทั้งหมดที่จำหน่ายในช่วงนี้ — ตัวหารของ "อัตราผู้ป่วยใน"
   *
   * ตัวชี้วัดระดับชาติคิดต่อแสนประชากร แต่ HIS ไม่มีทะเบียนประชากรรายปีที่ใช้
   * เป็นตัวหารได้ (ตาราง person มีทุกคนที่เคยลงทะเบียน ไม่ได้แยกปีและไม่ได้ตัด
   * คนที่ย้ายหรือเสียชีวิต) จึงรายงานเป็นสัดส่วนของผู้ป่วยในทั้งหมดแทน พร้อม
   * บอกคนอ่านว่าคนละตัวหารกับตัวชี้วัดระดับชาติ
   */
  admissions: number
  /**
   * การใช้ยาสูดพ่นของผู้ป่วย COPD จำแนกตามขั้นของยา
   *
   * ขอบเขตต่างจากสองตัวชี้วัดข้างบนโดยสิ้นเชิง — ที่นี่เป็น**ผู้ป่วยนอก** นับตาม
   * วันมารับบริการ (opitemrece.vstdate) และกลุ่มผู้ป่วยคือคนที่**เคย**มีรหัส J44
   * เป็นโรคหลักของผู้ป่วยนอกไม่จำกัดปี ส่วนสองตัวชี้วัดข้างบนเป็นผู้ป่วยในนับตาม
   * วันจำหน่าย ตัวเลขสองฝั่งจึงเอามาหารกันไม่ได้
   */
  drugs: CopdDrugs
}

/**
 * ขั้นของยาสูดพ่นที่ผู้ป่วย COPD ได้รับ — เรียงจากขั้นสูงสุดลงไป
 *
 * สี่ขั้นนี้มาจากคิวรีที่ได้รับมา ซึ่งตั้งลำดับความสำคัญไว้ D > C > B > A แล้ว
 * ยึด**ขั้นสูงสุดที่ผู้ป่วยได้รับในปีงบนั้น** คนหนึ่งจึงอยู่ขั้นเดียวต่อหนึ่งปีงบ
 * ผลรวมของสี่ขั้นจึงเท่ากับจำนวนผู้ป่วยที่ได้รับยาในรายการ และวางเป็นแท่งซ้อนได้
 *
 * **ชื่อขั้นในคิวรีต้นฉบับอ่านว่าเป็นยาคู่ (Spiriva_Symbicort) แต่เงื่อนไขไม่ได้
 * บังคับว่าต้องได้ Spiriva ร่วม** — ตรวจกับฐานแล้วผู้ป่วยส่วนใหญ่ของทุกขั้นไม่ได้
 * รับ Spiriva เลย (ขั้น D 707 จาก 882 ปี-คน · ขั้น C 1,049 จาก 1,444 · ขั้น B
 * 1,953 จาก 2,532) ชื่อขั้นจึงเป็นป้ายของระดับยา ไม่ใช่คำบอกว่าได้ยาสองตัว
 * โค้ดนี้คงตรรกะเดิมไว้ แต่นับจำนวนที่ได้ Spiriva ร่วมจริงมาด้วย (withSpiriva)
 * ให้หน้าจอบอกได้ว่าชื่อกับของจริงต่างกันเท่าไร
 */
export const COPD_DRUG_TIERS = ['symbicort', 'seretide', 'evoflo', 'spiriva'] as const

export type CopdDrugTier = (typeof COPD_DRUG_TIERS)[number]

export type CopdDrugTierCount = {
  /** ผู้ป่วย (HN) ที่ขั้นสูงสุดของปีนั้นคือขั้นนี้ */
  patients: number
  /** ในจำนวนนั้น ที่ได้รับ Spiriva ร่วมในปีเดียวกันจริง */
  withSpiriva: number
  /** ในจำนวนนั้น ที่ได้รับยาสูดพ่นนอกรายการร่วมด้วย */
  withOutside: number
}

/**
 * การใช้ยาสูดพ่นของผู้ป่วย COPD ในหนึ่งช่วงเวลา
 *
 * หน่วยนับคือ **ผู้ป่วยหนึ่งคนต่อหนึ่งช่วง** ไม่ใช่จำนวนใบสั่งยาและไม่ใช่จำนวนคน
 * ที่ไม่ซ้ำตลอดช่วง — คนที่มารับยาสามปีงบนับสามครั้งในสามแถว ผลรวมข้ามปีจึงไม่ใช่
 * จำนวนผู้ป่วยที่ไม่ซ้ำ
 */
export type CopdDrugs = {
  tiers: Record<CopdDrugTier, CopdDrugTierCount>
  /**
   * ผู้ป่วยที่ได้ยาสูดพ่น**นอกรายการเจ็ดรหัส**ที่ได้รับมา (ปัจจุบันคือ Spiolto
   * Respimat ซึ่งเป็น tiotropium + olodaterol)
   *
   * วัดแล้วเพิ่มเร็ว: 8 ราย (ปีงบ 2566) · 17 · 66 · 104 (ปีงบ 2569) ยาตัวนี้ไม่ได้
   * อยู่ในลำดับขั้นที่ได้รับมา จึงจัดขั้นให้เองไม่ได้ ต้องให้คณะกรรมการตัดสิน
   */
  outside: number
  /**
   * ในจำนวนนั้น ที่ได้ยานอกรายการ**อย่างเดียว** ไม่ได้ยาในรายการเลยในช่วงนั้น
   *
   * กลุ่มนี้หายไปจากรายงานทั้งหมดถ้านับตามรายการเดิม — ปีงบ 2569 มี 57 ราย
   *
   * นับตามช่วงที่ดูอยู่ ไม่ใช่ตลอดห้าปี ตัวเลขรายเดือนจึงสูงเมื่อเทียบกับ outside
   * (เช่น 27 จาก 30 ในเดือนเดียว) เพราะในหนึ่งเดือนผู้ป่วยมักได้ยาสูดพ่นตัวเดียว
   * คนที่ได้ยาในรายการเดือนอื่นจึงไม่ถูกหักออกจากเดือนนี้
   */
  outsideOnly: number
}
