/**
 * ชนิดของกล้ามเนื้อหัวใจตายเฉียบพลัน แยกตามรหัส ICD-10
 *
 * **ตัวชี้วัดที่ได้รับมาพูดถึง STEMI แต่คิวรีนับทุกชนิด** — ช่วง I21-I23 รวม
 * NSTEMI (I214) ซึ่งในฐานนี้มีมากกว่า STEMI สามเท่ากว่า จึงต้องแยกกลุ่มให้เลือกดู
 * ไม่ใช่รายงานยอดรวมแล้วเรียกว่า STEMI
 *
 *   stemi  I210-I213  ST-elevation — ตัวชี้วัดที่มีเกณฑ์ไม่เกินร้อยละ 9 หมายถึงกลุ่มนี้
 *   nstemi I214       Non-ST-elevation (acute subendocardial)
 *   other  I219 I22 I23  ไม่ระบุชนิด · กล้ามเนื้อหัวใจตายซ้ำ · ภาวะแทรกซ้อนหลังจาก
 *   all    ทั้งช่วง    ยอดที่คิวรีที่ได้รับมาคำนวณจริง
 *
 * สามกลุ่มแรก**แบ่งผู้ป่วยออกจากกันหมด** ไม่ซ้อนกัน เพราะหนึ่งการนอนมีโรคหลัก
 * ได้รหัสเดียว — บวกกันได้เท่ากับ all พอดี และวางเป็นแท่งซ้อนได้จริง
 */
export const MI_GROUPS = ['stemi', 'nstemi', 'other', 'all'] as const

export type MiGroup = (typeof MI_GROUPS)[number]

/** สามกลุ่มที่แบ่งผู้ป่วยออกจากกันหมด — ใช้กับกราฟแท่งซ้อนและตารางที่ต้องบวกได้ */
export const MI_PARTS: MiGroup[] = ['stemi', 'nstemi', 'other']

/**
 * เกณฑ์อัตราตายของ STEMI — ไม่เกินร้อยละ 9 ตามชื่อตัวชี้วัดที่ได้รับมา
 *
 * **ข้อเดียวในทั้งระบบที่มีเกณฑ์มาด้วย** หน้าอื่น (Stroke, Sepsis, COPD) ยังไม่มี
 * เกณฑ์ที่ตกลงกันไว้เลยจึงไม่ตัดสินผ่าน/ไม่ผ่าน ที่นี่ตัดสินได้ แต่เฉพาะกลุ่ม
 * STEMI เท่านั้น — เกณฑ์นี้ไม่ได้นิยามไว้สำหรับ NSTEMI หรือยอดรวม การเอาไปตัดสิน
 * กลุ่มอื่นจึงไม่ถูก หน้าจอจะไม่ลากเส้นเกณฑ์เมื่อดูกลุ่มอื่น
 */
export const STEMI_MORTALITY_TARGET = 9

export type CardiacCount = {
  /** การนอนโรงพยาบาล (AN) ที่เข้ากลุ่มนี้ */
  total: number
  /** ในกลุ่มนั้น ที่จำหน่ายด้วยสถานะเสียชีวิต (dchtype 08, 09) */
  dead: number
}

/**
 * กลุ่มของโรคหัวใจขาดเลือด แยกตามสามหลักแรกของรหัส ICD-10
 *
 * ตัวชี้วัดที่สอง "อัตราป่วยโรคหัวใจขาดเลือด" ครอบช่วง I20-I25 ซึ่ง**กว้างกว่า
 * ตัวชี้วัดกล้ามเนื้อหัวใจตายข้างต้น และครอบมันไว้ทั้งหมด** — บล็อก mi ที่นี่คือ
 * ขอบเขตเดียวกับ MI_GROUPS.all ตรงตัว (I21 I22 I23) ไม่ใช่ตัวเลขชุดใหม่ที่คิดแยก
 * คนอ่านจึงเห็นได้ว่ายอด MI เป็นส่วนย่อยของยอด IHD เท่าไร
 *
 *   angina     I20  เจ็บเค้นหัวใจ (angina pectoris)
 *   mi         I21 I22 I23  กล้ามเนื้อหัวใจตายเฉียบพลัน + ตายซ้ำ + ภาวะแทรกซ้อน
 *   otherAcute I24  โรคหัวใจขาดเลือดเฉียบพลันแบบอื่น
 *   chronic    I25  โรคหัวใจขาดเลือดเรื้อรัง
 *
 * สี่บล็อก**แบ่งผู้ป่วยออกจากกันหมด** ไม่ซ้อนกัน (โรคหลักมีรหัสเดียวต่อการนอน)
 * บวกกันได้เท่า ihdTotal พอดี และวางเป็นแท่งซ้อนได้จริง
 */
export const IHD_BLOCKS = ['angina', 'mi', 'otherAcute', 'chronic'] as const

export type IhdBlock = (typeof IHD_BLOCKS)[number]

export type CardiacPeriod = {
  /** คีย์ของช่วง — ปีงบเป็น '2569' เดือนเป็น '2026-01' */
  key: string
  partial: boolean
  /** กล้ามเนื้อหัวใจตายเฉียบพลันแยกชนิด — ขอบเขต I21-I23 ของตัวชี้วัดแรก */
  groups: Record<MiGroup, CardiacCount>
  /** โรคหัวใจขาดเลือดทั้งช่วง I20-I25 แยกบล็อก — ตัวชี้วัดที่สอง */
  ihd: Record<IhdBlock, CardiacCount>
  /** ยอดรวมของทั้งช่วง I20-I25 — เท่ากับผลบวกของสี่บล็อกพอดี */
  ihdTotal: CardiacCount
  /**
   * การนอนโรงพยาบาลทั้งหมดในช่วงนี้ ไม่ใช่เฉพาะโรคหัวใจ
   *
   * เป็นตัวหารของ "อัตราป่วย" ที่ข้อมูลนี้ตอบได้ — ตัวชี้วัดระดับชาติคิดต่อแสน
   * ประชากร ซึ่ง HIS ไม่มีตัวหารนั้น (ไม่มีทะเบียนประชากรที่มีมิติปี) จึงคิดต่อ
   * ผู้ป่วยในหนึ่งพันรายแทน และประกาศการแทนนี้ไว้ทุกที่ที่แสดงอัตรา
   */
  admissions: number
}

/**
 * รหัสหนึ่งรหัสที่ลงเป็นโรคหลัก ตลอดช่วงที่ดู
 *
 * มีไว้ให้คนอ่านตรวจได้ว่ายอดของแต่ละกลุ่มมาจากรหัสอะไรบ้าง — ตัวชี้วัดนี้ขึ้นกับ
 * การเลือกช่วงรหัสทั้งหมด ถ้าไม่แสดงรายรหัสไว้ คนอ่านไม่มีทางรู้ว่า NSTEMI ถูกนับ
 * รวมอยู่หรือไม่
 */
export type CardiacCode = {
  code: string
  /** ชื่อไทยของรหัส — มาจากตารางป้ายในโค้ด ไม่ได้อ่านจากทะเบียน ICD ของ HIS */
  name: string
  /**
   * ชนิดของกล้ามเนื้อหัวใจตายที่รหัสนี้นับเข้า — **null ถ้าไม่ใช่กล้ามเนื้อหัวใจตาย**
   *
   * รหัส I20 และ I25 อยู่ในขอบเขตโรคหัวใจขาดเลือดแต่ไม่ใช่กล้ามเนื้อหัวใจตาย
   * ถ้าปล่อยให้ตกไปอยู่กลุ่ม other ยอด MI จะบวมขึ้นเงียบ ๆ จึงต้องแยกเป็น null
   */
  group: MiGroup | null
  /** บล็อกโรคหัวใจขาดเลือดที่รหัสนี้นับเข้า — ทุกรหัสในขอบเขตมีค่านี้แน่นอน */
  block: IhdBlock
  count: CardiacCount
}
